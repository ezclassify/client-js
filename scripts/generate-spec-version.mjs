#!/usr/bin/env node
/**
 * Stamps src/spec-version.ts with the current info.version from
 * vendor/spec/openapi.yaml so CLIENT_SPEC_VERSION never drifts from the wire
 * spec it was compiled against.
 *
 * Run via: node scripts/generate-spec-version.mjs
 *
 * Called as the first command of the `build`, `test` and `typecheck` scripts,
 * not as a `prebuild`/`pretest` lifecycle hook: .npmrc sets
 * `ignore-scripts=true`, so a hook would silently never run.
 *
 * The file is written only when its bytes change. Rewriting it with the same
 * bytes moves its file time, and a build freshness check that compares source
 * times with output times then calls a finished build stale after nothing more
 * than a test run.
 *
 * @module
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const clientDir = resolve(here, '..');

/**
 * Bring a repository's spec-version stamp up to date with its vendored spec.
 *
 * @param options - `root` is the repository root to stamp.
 * @returns The version stamped, and whether the file had to be written.
 * @throws {Error} When the vendored spec has no `info.version`, or one that is
 *   not a version.
 */
export function stampSpecVersion({ root = clientDir } = {}) {
    const openapiRaw = readFileSync(
        resolve(root, 'vendor/spec/openapi.yaml'),
        'utf-8',
    );
    // Scoped to the `info:` block rather than matched document-wide: a
    // two-space `version:` key appears under schemas and examples too, and the
    // first one in the file is not necessarily the contract's own.
    const infoBlock = openapiRaw.split(/^info:\s*$/m)[1]?.split(/^\S/m)[0];
    if (infoBlock === undefined)
        throw new Error('No info block found in vendor/spec/openapi.yaml');
    const versionMatch = infoBlock.match(/^  version:\s+(\S+)/m);
    if (!versionMatch)
        throw new Error('No info.version found in vendor/spec/openapi.yaml');
    const specVersion = versionMatch[1];
    // The value is interpolated into a TypeScript string literal below, so it
    // has to be a version and nothing else.
    if (!/^[A-Za-z0-9][A-Za-z0-9.+-]*$/.test(specVersion))
        throw new Error(
            `info.version in vendor/spec/openapi.yaml is not a version: ${specVersion}`,
        );

    const output = [
        '// @generated: Do not edit. Regenerated by scripts/generate-spec-version.mjs.',
        '/**',
        ' * OpenAPI spec version this client was compiled against.',
        ' *',
        ' * Auto-generated from vendor/spec/openapi.yaml info.version. Do not edit',
        ' * directly. A mismatch between this value and the wire version returned by a',
        ' * live server indicates a version skew that may cause subtle behavioral',
        ' * differences.',
        ' */',
        `export const CLIENT_SPEC_VERSION = '${specVersion}';`,
        '',
    ].join('\n');

    const target = resolve(root, 'src/spec-version.ts');
    if (existsSync(target) && readFileSync(target, 'utf-8') === output) {
        return { version: specVersion, written: false };
    }
    writeFileSync(target, output, 'utf-8');
    return { version: specVersion, written: true };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const { version, written } = stampSpecVersion();
    console.log(
        written
            ? `Generated spec-version.ts (CLIENT_SPEC_VERSION=${version})`
            : `spec-version.ts is current (CLIENT_SPEC_VERSION=${version})`,
    );
}
